// Real, on-device AI super-resolution using the bundled Real-ESRGAN
// TFLite model (assets/models/realesrgan_x4.tflite).
//
// The model has a FIXED shape: input [1,50,50,3] float32 (raw 0-255 pixel
// values, NOT normalised) -> output [1,200,200,3] float32 (4x per tile).
// There is no dynamic input size, so large images are processed as a grid
// of overlapping 50x50 tiles that get stitched back together. The overlap
// (and cropping the blended edge of each tile's output) avoids the visible
// grid-seam artifacts you get from naive non-overlapping tiling.
//
// Everything below runs inside a single spawned Isolate — model load,
// tiling loop, and inference all happen off the UI thread, and the whole
// thing is killable via Isolate.kill() for instant cancellation.

import 'dart:io';
import 'dart:isolate';
import 'dart:typed_data';
import 'package:image/image.dart' as img;
import 'package:tflite_flutter/tflite_flutter.dart';

// Fixed model geometry.
const int kTileIn = 50;
const int kTileOut = 200;
const int kModelScale = 4;
const int kPad = 4; // input-side overlap; output-side overlap = kPad * 4
const int kStepIn = kTileIn - 2 * kPad; // 42
const int kStepOut = kStepIn * kModelScale; // 168

class RealEsrganArgs {
  const RealEsrganArgs({
    required this.imageBytes,
    required this.modelBytes,
    required this.targetScale, // 2 or 4 (final scale requested by user)
    required this.denoise, // 0.0-1.0, pre-pass before the AI model
    required this.outPath,
    required this.sendPort,
    required this.progressPort,
  });

  final Uint8List imageBytes;
  final Uint8List modelBytes;
  final int targetScale;
  final double denoise;
  final String outPath;
  final SendPort sendPort;
  final SendPort progressPort;
}

void _progress(SendPort port, double p, String label) => port.send([p, label]);

/// Isolate entry point. Sends the output file path (String) on success,
/// or an error message (String prefixed with 'AI_ERROR:') on failure so
/// the caller can decide whether to fall back to the bicubic path.
Future<void> runRealEsrgan(RealEsrganArgs args) async {
  final pp = args.progressPort;
  try {
    _progress(pp, 0.15, 'Decoding image…');
    img.Image? source = img.decodeImage(args.imageBytes);
    if (source == null) {
      args.sendPort.send('AI_ERROR: Could not decode image');
      return;
    }

    // The AI model always upscales 4x per tile. For a 2x request we
    // pre-shrink the source by half first, then run the SAME 4x model —
    // this lands on exactly 2x final scale, AND roughly quarters the tile
    // count vs. running 4x and downscaling after, which is why 2x mode is
    // noticeably faster.
    if (args.targetScale == 2) {
      source = img.copyResize(
        source,
        width: (source.width / 2).round().clamp(1, 1 << 20),
        height: (source.height / 2).round().clamp(1, 1 << 20),
        interpolation: img.Interpolation.average,
      );
    }

    // Cap tile count so this stays fast on-device. ~300 tiles is a good
    // balance of speed (a few seconds to ~20s on a modern phone CPU) vs.
    // final resolution. Bigger photos get pre-downscaled before tiling;
    // detail is still regenerated by the AI model, so this looks far
    // better than the same cap applied before a bicubic resize.
    const maxTiles = 320;
    var tilesX = ((source.width + kStepIn - 1) / kStepIn).ceil();
    var tilesY = ((source.height + kStepIn - 1) / kStepIn).ceil();
    if (tilesX * tilesY > maxTiles) {
      final ratio = (maxTiles / (tilesX * tilesY)).sqrt();
      final newW = (source.width * ratio).round().clamp(kStepIn, 1 << 20);
      final newH = (source.height * ratio).round().clamp(kStepIn, 1 << 20);
      _progress(
        pp,
        0.2,
        'Resizing input (${source.width}×${source.height} → $newW×$newH)…',
      );
      source = img.copyResize(
        source,
        width: newW,
        height: newH,
        interpolation: img.Interpolation.average,
      );
      tilesX = ((source.width + kStepIn - 1) / kStepIn).ceil();
      tilesY = ((source.height + kStepIn - 1) / kStepIn).ceil();
    }

    // Pre-denoise: GAN super-res models amplify whatever noise is already
    // in the input — phone camera grain becomes fake "texture" after 4x.
    // A single cheap smoothing pass before the AI model measurably cleans
    // up the output on noisy/low-light photos. Skipped entirely when the
    // slider is low, so it costs nothing by default.
    if (args.denoise > 0.15) {
      _progress(pp, 0.22, 'Pre-cleaning noise…');
      source = img.gaussianBlur(source, radius: args.denoise > 0.6 ? 2 : 1);
    }

    _progress(pp, 0.28, 'Loading AI model…');
    final interpreter = _createInterpreter(args.modelBytes);

    final srcW = source.width;
    final srcH = source.height;
    final srcBytes = source.getBytes(order: img.ChannelOrder.rgb);

    final outW = srcW * kModelScale;
    final outH = srcH * kModelScale;
    final outBuffer = Uint8List(outW * outH * 3);

    final totalTiles = tilesX * tilesY;
    var doneTiles = 0;

    // Reusable nested-list input buffer (tflite_flutter's documented,
    // version-stable feed format for a [1,50,50,3] tensor).
    final input = [
      List.generate(
        kTileIn,
        (_) => List.generate(kTileIn, (_) => List.filled(3, 0.0)),
      ),
    ];
    final output = [
      List.generate(
        kTileOut,
        (_) => List.generate(kTileOut, (_) => List.filled(3, 0.0)),
      ),
    ];

    for (var ty = 0; ty < tilesY; ty++) {
      for (var tx = 0; tx < tilesX; tx++) {
        final inX0 = tx * kStepIn - kPad;
        final inY0 = ty * kStepIn - kPad;

        // Fill the input tile, edge-replicating out-of-bounds pixels.
        for (var dy = 0; dy < kTileIn; dy++) {
          final sy = (inY0 + dy).clamp(0, srcH - 1);
          final rowBase = sy * srcW * 3;
          final row = input[0][dy];
          for (var dx = 0; dx < kTileIn; dx++) {
            final sx = (inX0 + dx).clamp(0, srcW - 1);
            final idx = rowBase + sx * 3;
            final px = row[dx];
            px[0] = srcBytes[idx].toDouble();
            px[1] = srcBytes[idx + 1].toDouble();
            px[2] = srcBytes[idx + 2].toDouble();
          }
        }

        interpreter.run(input, output);

        // Crop the overlap border from the output (except at true image
        // edges, where we keep the full crop since there's no neighbour
        // to blend with) and stitch into the final buffer.
        final cropL = tx == 0 ? 0 : kPad * kModelScale;
        final cropT = ty == 0 ? 0 : kPad * kModelScale;
        final cropR = tx == tilesX - 1 ? 0 : kPad * kModelScale;
        final cropB = ty == tilesY - 1 ? 0 : kPad * kModelScale;

        final destX0 = tx * kStepOut - (tx == 0 ? 0 : kPad * kModelScale);
        final destY0 = ty * kStepOut - (ty == 0 ? 0 : kPad * kModelScale);
        final tileOut = output[0];

        for (var y = cropT; y < kTileOut - cropB; y++) {
          final dy = destY0 + (y - cropT);
          if (dy < 0 || dy >= outH) continue;
          final rowBase = dy * outW * 3;
          final srcRow = tileOut[y];
          for (var x = cropL; x < kTileOut - cropR; x++) {
            final dx = destX0 + (x - cropL);
            if (dx < 0 || dx >= outW) continue;
            final px = srcRow[x];
            final o = rowBase + dx * 3;
            outBuffer[o] = px[0].clamp(0, 255).round();
            outBuffer[o + 1] = px[1].clamp(0, 255).round();
            outBuffer[o + 2] = px[2].clamp(0, 255).round();
          }
        }

        doneTiles++;
        if (doneTiles % 4 == 0 || doneTiles == totalTiles) {
          _progress(
            pp,
            0.3 + (doneTiles / totalTiles) * 0.6,
            'AI upscaling… ($doneTiles/$totalTiles tiles)',
          );
        }
      }
    }

    interpreter.close();

    _progress(pp, 0.94, 'Saving…');
    final result = img.Image.fromBytes(
      width: outW,
      height: outH,
      bytes: outBuffer.buffer,
      numChannels: 3,
      order: img.ChannelOrder.rgb,
    );
    // PNG, not JPEG: lossless, so the extra detail the AI model actually
    // generated survives in the file instead of getting thrown away by
    // JPEG compression. This is also why the output file is noticeably
    // bigger than the source — that size increase IS the added detail,
    // not padding.
    final encoded = img.encodePng(result);
    File(args.outPath).writeAsBytesSync(encoded);

    args.sendPort.send(args.outPath);
  } catch (e) {
    args.sendPort.send('AI_ERROR: $e');
  }
}

extension _DoubleSqrt on double {
  double sqrt() {
    if (this <= 0) return 0;
    var x = this / 2;
    for (var i = 0; i < 20; i++) {
      x = (x + this / x) / 2;
    }
    return x;
  }
}

// ── Interpreter creation: try GPU delegate first, fall back to CPU ────────
//
// The 50x50 tiles are tiny, so GPU delegate mainly helps by cutting
// per-tile dispatch overhead and using the phone's NPU/GPU instead of
// fighting the UI thread's CPU cores for cycles. On unsupported devices
// (older phones, emulators, desktop) delegate creation throws — we catch
// that and silently continue on plain CPU (with 4 threads + XNNPACK,
// which tflite_flutter enables by default), so this never breaks a run,
// it only sometimes speeds one up.
Interpreter _createInterpreter(Uint8List modelBytes) {
  final cpuOptions = InterpreterOptions()..threads = 4;

  if (Platform.isAndroid) {
    try {
      final gpuOptions = InterpreterOptions()..addDelegate(GpuDelegateV2());
      final gpuInterpreter = Interpreter.fromBuffer(
        modelBytes,
        options: gpuOptions,
      );
      // Some devices accept delegate creation but fail at allocation or
      // first invoke — probe both here so a bad GPU driver can't take
      // down the whole upscale, only lose the speed-up.
      gpuInterpreter.allocateTensors();
      final probeIn = [
        List.generate(
          kTileIn,
          (_) => List.generate(kTileIn, (_) => List.filled(3, 0.0)),
        ),
      ];
      final probeOut = [
        List.generate(
          kTileOut,
          (_) => List.generate(kTileOut, (_) => List.filled(3, 0.0)),
        ),
      ];
      gpuInterpreter.run(probeIn, probeOut);
      return gpuInterpreter;
    } catch (_) {
      // GPU delegate unavailable/unstable on this device — fall through.
    }
  }

  return Interpreter.fromBuffer(modelBytes, options: cpuOptions)
    ..allocateTensors();
}
