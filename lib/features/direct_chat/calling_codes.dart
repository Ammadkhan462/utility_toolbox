/// Preferred country when several share a calling code (e.g. +1, +7, +39).
const _primaryForDial = {'1': 'US', '7': 'RU', '39': 'IT', '262': 'RE', '599': 'CW'};

CallingCode? callingCodeForIso(String? iso) {
  if (iso == null) return null;
  final up = iso.toUpperCase();
  for (final c in callingCodes) {
    if (c.iso == up) return c;
  }
  return null;
}

/// Finds the country whose calling code is the longest prefix of
/// [e164Digits] (E.164 digits without '+').
CallingCode? callingCodeForNumber(String e164Digits, {String? preferIso}) {
  CallingCode? best;
  for (final c in callingCodes) {
    if (!e164Digits.startsWith(c.dial)) continue;
    if (best == null || c.dial.length > best.dial.length) {
      best = c;
    }
  }
  if (best == null) return null;
  // Same code shared by several countries: keep the user's own country if it
  // matches, otherwise the primary one.
  final prefer = callingCodeForIso(preferIso);
  if (prefer != null && prefer.dial == best.dial) return prefer;
  final primary = _primaryForDial[best.dial];
  return primary == null ? best : (callingCodeForIso(primary) ?? best);
}
